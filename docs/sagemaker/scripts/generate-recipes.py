"""Generate the SageMaker recipe pages from docs/sagemaker/recipes/*.json.

Writes one page per model to source/recipes/<model-slug>.md, the summary table in
source/recipes/index.md, and the recipe entries in source/_toctree.yml.
"""

from __future__ import annotations

import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RECIPES_DIR = ROOT / "recipes"
PAGES_DIR = ROOT / "source" / "recipes"
INDEX = PAGES_DIR / "index.md"
TOCTREE = ROOT / "source" / "_toctree.yml"

GENERATED_NOTE = (
    "<!-- This page is generated by scripts/generate-recipes.py from recipes/*.json. "
    "Do not edit it by hand. -->"
)
TABLE_START = "<!-- GENERATED RECIPES TABLE -->"
TABLE_END = "<!-- END GENERATED RECIPES TABLE -->"
TOC_START = "# GENERATED RECIPES DO NOT EDIT!"
TOC_END = "# END GENERATED RECIPES"

SUITES = ["single-request", "long-decode", "long-prefill", "concurrency", "prefix", "sharegpt"]
CAPABILITIES = [
    ("chat", "chat"),
    ("streaming", "streaming"),
    ("tool_calling", "tool calling"),
    ("reasoning", "reasoning"),
    ("vision", "vision"),
]
NA = "n/a"


def slug(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")


def fmt(value, digits: int) -> str:
    if value is None:
        return NA
    return f"{value:,.{digits}f}"


def per_user(metric: dict) -> float | None:
    tpot = metric.get("median_tpot_ms")
    return 1000 / tpot if tpot else None


def find_metric(recipe: dict, suite: str) -> dict:
    for metric in recipe["metrics"]:
        if metric["suite"] == suite:
            return metric
    return {}


def image_uri(recipe: dict, region: str) -> str:
    image = recipe["image"]
    base = f"{image['registry_account']}.dkr.ecr.{region}.amazonaws.com/{image['repository']}"
    if image["digest"]:
        return f"{base}@{image['digest']}"
    return f"{base}:{image['tag']}"


def load_recipes() -> list[dict]:
    recipes = []
    for path in sorted(RECIPES_DIR.glob("*.json")):
        recipe = json.loads(path.read_text())
        if recipe.get("schema_version") != 1:
            raise SystemExit(f"{path.name}: unsupported schema_version {recipe.get('schema_version')}")
        if path.stem != recipe["id"]:
            raise SystemExit(f"{path.name}: file name does not match id {recipe['id']}")
        recipes.append(recipe)
    return recipes


def sort_key(recipe: dict) -> tuple:
    return (recipe["model_id"].lower(), recipe["instance"]["type"], recipe["id"])


def capabilities_line(recipe: dict) -> str:
    caps = recipe["capabilities"]
    passed = [label for key, label in CAPABILITIES if caps.get(key) is True]
    failed = [label for key, label in CAPABILITIES if caps.get(key) is False]
    unknown = [label for key, label in CAPABILITIES if caps.get(key) is None]
    parts = []
    if passed:
        parts.append("validated: " + ", ".join(passed))
    if failed:
        parts.append("failed: " + ", ".join(failed))
    if unknown:
        parts.append("not recorded: " + ", ".join(unknown))
    text = "; ".join(parts)
    return text[0].upper() + text[1:]


def validation_line(recipe: dict) -> str:
    validation = recipe["validation"]
    text = validation["status"].capitalize()
    if validation["failed_checks"]:
        text += ". Failed checks: " + ", ".join(f"`{c}`" for c in validation["failed_checks"])
    return text


def metrics_table(recipe: dict) -> list[str]:
    if not recipe["metrics"]:
        return ["Benchmark results on SageMaker are not available for this recipe."]
    lines = [
        "| Suite | Concurrency | Input tokens | Output tokens | Output tok/s | Per-user tok/s | Requests/s | Median TTFT (ms) | Median TPOT (ms) | USD per 1M output tokens |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    order = {suite: i for i, suite in enumerate(SUITES)}
    for m in sorted(recipe["metrics"], key=lambda m: (order.get(m["suite"], len(SUITES)), m["suite"], m["concurrency"] or 0)):
        lines.append(
            "| "
            + " | ".join(
                [
                    m["suite"],
                    fmt(m["concurrency"], 0),
                    fmt(m["input_tokens"], 0),
                    fmt(m["output_tokens"], 0),
                    fmt(m["output_throughput"], 1),
                    fmt(per_user(m), 1),
                    fmt(m["request_throughput"], 2),
                    fmt(m["median_ttft_ms"], 1),
                    fmt(m["median_tpot_ms"], 1),
                    fmt(m["cost_per_million_output_tokens_usd"], 2),
                ]
            )
            + " |"
        )
    measured = recipe["measured"]
    if measured:
        lines += [
            "",
            f"Measured on {measured['date']} in `{measured['region']}` with `{measured['tool']}`, "
            f"maximum concurrency {measured['max_concurrency']}.",
        ]
    return lines


def deploy_snippet(recipe: dict) -> tuple[list[str], str]:
    instance = recipe["instance"]["type"]
    name = slug(f"{recipe['model_id'].split('/')[-1]}-{instance.removeprefix('ml.')}")[:63].strip("-")
    environment = json.dumps(recipe["deployment"]["environment"], indent=4, sort_keys=True)
    uri = image_uri(recipe, "{region}")
    return [
        "```python",
        "import os",
        "import boto3",
        "from sagemaker.core.helper.session_helper import Session, get_execution_role",
        "",
        "# AWS region where the endpoint runs",
        'region = "us-east-1"',
        f'name = "{name}"',
        "",
        "# set up the SageMaker session and execution role",
        "sess = Session(boto_session=boto3.Session(region_name=region))",
        "role = get_execution_role()",
        "sm = sess.boto_session.client(\"sagemaker\")",
        "",
        f'image = f"{uri}"',
        f"environment = {environment}",
        "# gated models need a Hugging Face token: read it from your environment",
        'if "HF_TOKEN" in os.environ:',
        '    environment["HF_TOKEN"] = os.environ["HF_TOKEN"]',
        "",
        "sm.create_model(",
        "    ModelName=name,",
        "    # IAM role with permissions to create an endpoint",
        "    ExecutionRoleArn=role,",
        '    PrimaryContainer={"Image": image, "Environment": environment},',
        ")",
        "sm.create_endpoint_config(",
        "    EndpointConfigName=name,",
        "    ProductionVariants=[",
        "        {",
        '            "VariantName": "AllTraffic",',
        '            "ModelName": name,',
        f'            "InstanceType": "{instance}",',
        '            "InitialInstanceCount": 1,',
        f'            "InferenceAmiVersion": "{recipe["deployment"]["inference_ami_version"]}",',
        f'            "ContainerStartupHealthCheckTimeoutInSeconds": {recipe["deployment"]["startup_health_check_timeout_s"]},',
        "        }",
        "    ],",
        ")",
        "sm.create_endpoint(EndpointName=name, EndpointConfigName=name)",
        "",
        "# wait up to 90 minutes for the endpoint to reach InService",
        'sm.get_waiter("endpoint_in_service").wait(',
        '    EndpointName=name, WaiterConfig={"Delay": 60, "MaxAttempts": 90}',
        ")",
        'print(f"{name} is InService")',
        "```",
    ], name


def cleanup_snippet(name: str) -> list[str]:
    return [
        "```python",
        "import boto3",
        "",
        "# AWS region where the endpoint runs",
        'region = "us-east-1"',
        f'name = "{name}"',
        "",
        'sm = boto3.client("sagemaker", region_name=region)',
        "sm.delete_endpoint(EndpointName=name)",
        "sm.delete_endpoint_config(EndpointConfigName=name)",
        "sm.delete_model(ModelName=name)",
        "```",
    ]


def recipe_section(recipe: dict, heading: str) -> list[str]:
    instance = recipe["instance"]
    image = recipe["image"]
    price = instance["price_per_hour_usd"]
    price_text = (
        f"{price:,.2f} USD per hour on demand in `{instance['price_region']}`" if price is not None else NA
    )
    dlc = f"`{image['repository']}:{image['tag']}`"
    if image["digest"]:
        dlc += f" (digest `{image['digest']}`)"
    revision = f"`{recipe['model_revision']}`" if recipe["model_revision"] else "latest on the Hub"
    context = f"{recipe['context_length']:,} tokens" if recipe["context_length"] is not None else NA
    snippet, name = deploy_snippet(recipe)
    return [
        f"## {heading}",
        "",
        f"- **Instance**: `{instance['type']}`, {instance['gpus']} x {instance['accelerator']} "
        f"({instance['gpu_memory_gb']} GB each), {price_text}",
        f"- **DLC**: {dlc}, vLLM {recipe['engine']['version']}",
        f"- **Model revision**: {revision}",
        f"- **Context length**: {context}",
        f"- **Capabilities**: {capabilities_line(recipe)}",
        f"- **Validation**: {validation_line(recipe)}",
        f"- **Recipe ID**: `{recipe['id']}`",
        "",
        "### Metrics",
        "",
        *metrics_table(recipe),
        "",
        "### Deploy",
        "",
        "This snippet creates the model, endpoint configuration, and endpoint with the recipe settings. "
        "Outside SageMaker Studio, replace `get_execution_role()` with the role lookup from "
        "[Set up the SDK](../tutorials/sagemaker-sdk/setup-sagemaker-sdk#execution-role). "
        "To send requests, see [Invoke the endpoint](./deploy-a-recipe#invoke-the-endpoint).",
        "",
        *snippet,
        "",
        "### Clean up",
        "",
        "Delete the endpoint, endpoint configuration, and model to stop billing:",
        "",
        *cleanup_snippet(name),
        "",
    ]


def model_page(model_id: str, recipes: list[dict]) -> str:
    updated = max(r["updated_at"] for r in recipes)
    counts = defaultdict(int)
    for recipe in recipes:
        counts[recipe["instance"]["type"]] += 1
    lines = [
        f"# {model_id} on Amazon SageMaker AI",
        "",
        GENERATED_NOTE,
        "",
        f"_Last updated: {updated}_",
        "",
        f"Recipes for [{model_id}](https://huggingface.co/{model_id}) with the Hugging Face vLLM DLC. "
        "Each section lists the instance, the pinned container, the engine settings, and the results "
        "measured on a SageMaker endpoint. Read [Recipes](./index) for how the measurements are taken.",
        "",
    ]
    for recipe in recipes:
        heading = recipe["instance"]["type"]
        if counts[heading] > 1:
            heading += f", recipe {recipe['id'].rsplit('--', 1)[-1]}"
        lines += recipe_section(recipe, heading)
    return "\n".join(lines).rstrip("\n") + "\n"


def summary_table(models: dict[str, list[dict]]) -> list[str]:
    lines = [
        "| Model | Instance | GPUs | vLLM DLC | Context length | Validation | Single-user tok/s | Median TTFT (ms) | Output tok/s at c64 | USD per hour | USD per 1M output tokens at c64 |",
        "|---|---|---|---|---:|---|---:|---:|---:|---:|---:|",
    ]
    for model_id, recipes in models.items():
        for recipe in recipes:
            single = find_metric(recipe, "single-request")
            concurrency = find_metric(recipe, "concurrency")
            instance = recipe["instance"]
            context = f"{recipe['context_length']:,}" if recipe["context_length"] is not None else NA
            lines.append(
                "| "
                + " | ".join(
                    [
                        f"[{model_id}](./{slug(model_id)})",
                        f"`{instance['type']}`",
                        f"{instance['gpus']} x {instance['accelerator']}",
                        recipe["engine"]["version"],
                        context,
                        recipe["validation"]["status"],
                        fmt(per_user(single), 1),
                        fmt(single.get("median_ttft_ms"), 1),
                        fmt(concurrency.get("output_throughput"), 1),
                        fmt(instance["price_per_hour_usd"], 2),
                        fmt(concurrency.get("cost_per_million_output_tokens_usd"), 2),
                    ]
                )
                + " |"
            )
    return lines


def replace_between(text: str, start: str, end: str, body: list[str], path: Path) -> str:
    pattern = re.compile(rf"(^[ \t]*{re.escape(start)}[ \t]*\n).*?(^[ \t]*{re.escape(end)}[ \t]*$)", re.S | re.M)
    if not pattern.search(text):
        raise SystemExit(f"{path}: markers {start!r} / {end!r} not found")
    block = "".join(line + "\n" for line in body)
    return pattern.sub(lambda m: m.group(1) + block + m.group(2), text, count=1)


def write_if_changed(path: Path, content: str) -> None:
    if not path.exists() or path.read_text() != content:
        path.write_text(content)
        print(f"wrote {path.relative_to(ROOT)}")


def main() -> None:
    models: dict[str, list[dict]] = defaultdict(list)
    for recipe in sorted(load_recipes(), key=sort_key):
        models[recipe["model_id"]].append(recipe)
    models = dict(sorted(models.items(), key=lambda item: item[0].lower()))

    pages = {PAGES_DIR / f"{slug(model_id)}.md": model_page(model_id, recipes) for model_id, recipes in models.items()}
    for path in sorted(PAGES_DIR.glob("*.md")):
        if path not in pages and GENERATED_NOTE in path.read_text():
            path.unlink()
            print(f"removed {path.relative_to(ROOT)}")
    for path, content in pages.items():
        write_if_changed(path, content)

    index = INDEX.read_text()
    write_if_changed(INDEX, replace_between(index, TABLE_START, TABLE_END, ["", *summary_table(models), ""], INDEX))

    toc_entries = []
    for model_id in models:
        toc_entries += [f"    - local: recipes/{slug(model_id)}", f"      title: {json.dumps(model_id)}"]
    toctree = TOCTREE.read_text()
    write_if_changed(TOCTREE, replace_between(toctree, TOC_START, TOC_END, toc_entries, TOCTREE))


if __name__ == "__main__":
    main()
