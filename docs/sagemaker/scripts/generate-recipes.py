def slug(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")


def esc(value) -> str:
    return html.escape(str(value), quote=True)


def fmt(value, digits: int) -> str:
    if value is None:
        return NA
    return f"{value:,.{digits}f}"


def usd(value) -> str:
    if value is None:
        return NA
    return f"${value:,.2f}"


def per_user(metric: dict) -> float | None:
    tpot = metric.get("median_tpot_ms")
    return 1000 / tpot if tpot else None


def find_metric(recipe: dict, suite: str) -> dict:
    for metric in recipe["metrics"]:
        if metric["suite"] == suite:
            return metric
    return {}


def image_reference(recipe: dict) -> str:
    image = recipe["image"]
    return f"{image['repository']}@{image['digest']}" if image["digest"] else f"{image['repository']}:{image['tag']}"


def image_uri(recipe: dict, region: str) -> str:
    return f"{recipe['image']['registry_account']}.dkr.ecr.{region}.amazonaws.com/{image_reference(recipe)}"


def endpoint_name(recipe: dict) -> str:
    name = slug(f"{recipe['model_id'].split('/')[-1]}-{recipe['instance']['type'].removeprefix('ml.')}")
    if not name[0].isalpha():
        name = f"hf-{name}"
    return name[:63].strip("-")


def template_url(recipe: dict) -> str:
    return f"{TEMPLATE_BASE_URL}{recipe['id']}.json"


def console_url(recipe: dict, region: str) -> str:
    query = urllib.parse.urlencode(
        {"templateURL": template_url(recipe), "stackName": endpoint_name(recipe), "param_EndpointName": endpoint_name(recipe)}
    )
    return f"https://{region}.console.aws.amazon.com/cloudformation/home?region={region}#/stacks/quickcreate?{query}"


def load_recipes() -> list[dict]:
    recipes = []
    for path in sorted(RECIPES_DIR.glob("*.json")):
        recipe = json.loads(path.read_text())
        if recipe.get("schema_version") != 1:
            raise SystemExit(f"{path.name}: unsupported schema_version {recipe.get('schema_version')}")
        if path.stem != recipe["id"]:
            raise SystemExit(f"{path.name}: file name does not match id {recipe['id']}")
        recipes.append(recipe)
    return recipes


def sort_key(recipe: dict) -> tuple:
    price = recipe["instance"]["price_per_hour_usd"]
    return (recipe["model_id"].lower(), price is None, price or 0, recipe["instance"]["type"], recipe["id"])


def hub_info(model_id: str) -> dict:
    query = "&".join(f"expand[]={field}" for field in ["gated", "pipeline_tag", "safetensors", "cardData"])
    url = f"{HUB_API}{model_id}?{urllib.parse.quote(query, safe='=&')}"
    with urllib.request.urlopen(url, timeout=30) as response:
        info = json.load(response)
    card = info.get("cardData") or {}
    return {
        "gated": bool(info.get("gated")),
        "task": info.get("pipeline_tag"),
        "parameters": (info.get("safetensors") or {}).get("total"),
        "license": card.get("license"),
    }


def task_label(task: str | None) -> str | None:
    labels = {"text-generation": "Text generation", "image-text-to-text": "Image-text-to-text"}
    if task is None:
        return None
    return labels.get(task, task.replace("-", " ").capitalize())


def parameters_label(parameters: int | None) -> str | None:
    if not parameters:
        return None
    return f"{parameters / 1e9:,.1f}B parameters" if parameters < 100e9 else f"{parameters / 1e9:,.0f}B parameters"


def size_bucket(parameters: int | None) -> str:
    if not parameters:
        return ""
    for key, _, limit in SIZES:
        if limit is None or parameters < limit:
            return key
    return ""


