def replace_between(text: str, start: str, end: str, body: list[str], path: Path) -> str:
    pattern = re.compile(rf"(^[ \t]*{re.escape(start)}[ \t]*\n).*?(^[ \t]*{re.escape(end)}[ \t]*$)", re.S | re.M)
    if not pattern.search(text):
        raise SystemExit(f"{path}: markers {start!r} / {end!r} not found")
    block = "".join(line + "\n" for line in body)
    return pattern.sub(lambda m: m.group(1) + block + m.group(2), text, count=1)


def write_if_changed(path: Path, content: str) -> None:
    if not path.exists() or path.read_text() != content:
        path.write_text(content)
        print(f"wrote {path.relative_to(ROOT)}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--fetch", action="store_true", help=f"download recipes.jsonl from {DATASET} first")
    args = parser.parse_args()
    if args.fetch:
        fetch_snapshot()

    models: dict[str, list[dict]] = defaultdict(list)
    for recipe in sorted(load_recipes(), key=sort_key):
        models[recipe["model_id"]].append(recipe)
    models = dict(sorted(models.items(), key=lambda item: item[0].lower()))
    infos = {model_id: hub_info(model_id) for model_id in models}

    pages = {PAGES_DIR / f"{slug(model_id)}.md": model_page(model_id, model_recipes, infos[model_id]) for model_id, model_recipes in models.items()}
    pages[INDEX] = index_page(models, infos)
    for path in sorted(PAGES_DIR.glob("*.md")):
        if path not in pages and "<!-- This page is generated by scripts/generate-recipes.py" in path.read_text():
            path.unlink()
            print(f"removed {path.relative_to(ROOT)}")
    for path, content in pages.items():
        write_if_changed(path, content)

    labs: dict[str, list[str]] = defaultdict(list)
    for model_id in models:
        labs[infos[model_id]["org_name"]].append(model_id)
    toc_entries = []
    for lab in sorted(labs, key=str.lower):
        toc_entries += [f"    - title: {json.dumps(lab)}", "      isExpanded: false", "      sections:"]
        for model_id in labs[lab]:
            toc_entries += [
                f"        - local: recipes/{slug(model_id)}",
                f"          title: {json.dumps(model_id.split('/', 1)[1])}",
            ]
    toctree = TOCTREE.read_text()
    write_if_changed(TOCTREE, replace_between(toctree, TOC_START, TOC_END, toc_entries, TOCTREE))


if __name__ == "__main__":
    main()
