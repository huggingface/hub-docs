def model_page(model_id: str, recipes: list[dict], info: dict) -> str:
    counts = defaultdict(int)
    for recipe in recipes:
        counts[recipe["instance"]["type"]] += 1
    anchors = {r["id"]: recipe_anchor(r, counts[r["instance"]["type"]] > 1) for r in recipes}
    facts = [fact for fact in [task_label(info["task"]), parameters_label(info["parameters"])] if fact]
    if info["license"]:
        facts.append(f"license `{info['license']}`")
    if info["gated"]:
        facts.append("gated: needs a Hugging Face token")
    measured = [r for r in recipes if r["measured"]]
    count = f"{len(recipes)} recipe" + ("s" if len(recipes) > 1 else "")
    last = max((r["measured"]["date"] for r in measured if r["measured"]["date"]), default=None)
    when = f" on {last}" if last else ""
    if len(recipes) == 1:
        status = f"measured on a real SageMaker endpoint{when}" if measured else "not measured on SageMaker yet"
    else:
        status = f"{len(measured)} of them measured on a real SageMaker endpoint{', last' + when if last else ''}" if measured else "none of them measured on SageMaker yet"
    lines = [
        f"# Deploy {model_id} on Amazon SageMaker AI",
        "",
        GENERATED_NOTE,
        "",
        f"[{model_id}](https://huggingface.co/{model_id}) ({', '.join(facts)}) has {count} for SageMaker AI, {status}. "
        "Each recipe pins the container, the instance, and the engine settings. [Browse all recipes](./index).",
        "",
    ]
    if len(recipes) > 1:
        lines += [*overview_table(recipes, anchors), ""]
    for recipe in recipes:
        lines += recipe_section(recipe, anchors[recipe["id"]], info["gated"])
    lines += invoke_section(model_id, recipes[0])
    return "\n".join(lines).rstrip("\n") + "\n"


