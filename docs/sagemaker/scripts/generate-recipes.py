def slug(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")


def esc(value) -> str:
    return html.escape(str(value), quote=True)


def fmt(value, digits: int) -> str:
    if value is None:
        return NA
    return f"{value:,.{digits}f}"


def usd(value) -> str:
    if value is None:
        return NA
    return f"${value:,.2f}"


def per_user(metric: dict) -> float | None:
    tpot = metric.get("median_tpot_ms")
    return 1000 / tpot if tpot else None


def find_metric(recipe: dict, suite: str) -> dict:
    for metric in recipe["metrics"]:
        if metric["suite"] == suite:
            return metric
    return {}


def image_reference(recipe: dict) -> str:
    image = recipe["image"]
    return f"{image['repository']}@{image['digest']}" if image["digest"] else f"{image['repository']}:{image['tag']}"


def image_uri(recipe: dict, region: str) -> str:
    return f"{recipe['image']['registry_account']}.dkr.ecr.{region}.amazonaws.com/{image_reference(recipe)}"


def endpoint_name(recipe: dict) -> str:
    name = slug(f"{recipe['model_id'].split('/')[-1]}-{recipe['instance']['type'].removeprefix('ml.')}")
    if not name[0].isalpha():
        name = f"hf-{name}"
    return name[:63].strip("-")


def console_url(recipe: dict, region: str) -> str:
    query = urllib.parse.urlencode(
        {"templateURL": recipe["template_url"], "stackName": endpoint_name(recipe), "param_EndpointName": endpoint_name(recipe)}
    )
    return f"https://console.aws.amazon.com/cloudformation/home?region={region}#/stacks/quickcreate?{query}"


def hub_token() -> str | None:
    token = os.environ.get("HF_TOKEN")
    if token:
        return token
    cached = Path(os.environ.get("HF_HOME", Path.home() / ".cache" / "huggingface")) / "token"
    return cached.read_text().strip() if cached.exists() else None


def fetch_snapshot() -> None:
    token = hub_token()
    if not token:
        raise SystemExit(f"--fetch needs a Hugging Face token that can read {DATASET}: set HF_TOKEN or run `hf auth login`.")
    request = urllib.request.Request(DATASET_INDEX_URL, headers={"Authorization": f"Bearer {token}"})
    with urllib.request.urlopen(request, timeout=60) as response:
        content = response.read().decode()
    write_if_changed(SNAPSHOT, content)


def recipe_from_row(row: dict, line: int) -> dict:
    missing = [field for field in ROW_FIELDS if field not in row]
    if missing:
        raise SystemExit(
            f"{SNAPSHOT.name}:{line}: missing {', '.join(missing)}. Sync the dataset with a Kitchen version that exports the catalog fields."
        )
    match = IMAGE_PATTERN.match(row["image"])
    if not match:
        raise SystemExit(f"{SNAPSHOT.name}:{line}: unsupported image {row['image']}")
    account, repository, tag, digest = match.groups()
    return {
        "id": f"{slug(row['model_id'])}--{row['recipe']}",
        "name": row["recipe"],
        "model_id": row["model_id"],
        "model_revision": row["model_revision"],
        "context_length": row["context_length"],
        "engine": row["engine"],
        "image": {"registry_account": account, "repository": repository, "tag": tag, "digest": digest},
        "instance": row["instance"],
        "instance_types": row["instance_types"],
        "deployment": {**row["deployment"], "environment": json.loads(row["environment"])},
        "measured": row["measured"],
        "capabilities": row["capabilities"],
        "failed_checks": row["failed_checks"],
        "metrics": row["metrics"],
        "template_url": row["cloudformation_template_url"],
    }


def load_recipes() -> list[dict]:
    if not SNAPSHOT.exists():
        raise SystemExit(f"{SNAPSHOT} not found: run `python scripts/generate-recipes.py --fetch` first.")
    recipes = {}
    for line, text in enumerate(SNAPSHOT.read_text().splitlines(), start=1):
        if text.strip():
            recipe = recipe_from_row(json.loads(text), line)
            recipes.setdefault(recipe["id"], recipe)
    return list(recipes.values())


def sort_key(recipe: dict) -> tuple:
    price = recipe["instance"]["price_per_hour_usd"]
    return (recipe["model_id"].lower(), recipe["measured"] is None, price is None, price or 0, recipe["instance"]["type"], recipe["id"])


@functools.cache
def owner_profile(owner: str) -> dict:
    for kind in ("organizations", "users"):
        try:
            with urllib.request.urlopen(f"https://huggingface.co/api/{kind}/{owner}/overview", timeout=30) as response:
                profile = json.load(response)
        except urllib.error.HTTPError as error:
            if error.code == 404:
                continue
            raise
        return {"name": profile.get("fullname") or owner, "avatar": profile.get("avatarUrl")}
    raise SystemExit(f"Hub owner not found: {owner}")


def hub_info(model_id: str) -> dict:
    query = "&".join(f"expand[]={field}" for field in ["gated", "pipeline_tag", "safetensors", "cardData"])
    url = f"{HUB_API}{model_id}?{urllib.parse.quote(query, safe='=&')}"
    with urllib.request.urlopen(url, timeout=30) as response:
        info = json.load(response)
    card = info.get("cardData") or {}
    owner = owner_profile(info["id"].split("/")[0])
    return {
        "org_name": owner["name"],
        "org_avatar": owner["avatar"],
        "gated": bool(info.get("gated")),
        "task": info.get("pipeline_tag"),
        "parameters": (info.get("safetensors") or {}).get("total"),
        "license": card.get("license"),
    }


def task_label(task: str | None) -> str | None:
    labels = {"text-generation": "Text generation", "image-text-to-text": "Image-text-to-text"}
    if task is None:
        return None
    return labels.get(task, task.replace("-", " ").capitalize())


def parameters_label(parameters: int | None) -> str | None:
    if not parameters:
        return None
    return f"{parameters / 1e9:,.1f}B parameters" if parameters < 100e9 else f"{parameters / 1e9:,.0f}B parameters"


def size_bucket(parameters: int | None) -> str:
    if not parameters:
        return ""
    for key, _, limit in SIZES:
        if limit is None or parameters < limit:
            return key
    return ""


def gpu_label(recipe: dict) -> str:
    instance = recipe["instance"]
    if not instance["accelerator"]:
        return NA
    return f"{instance['gpus']} x {instance['accelerator']}" if instance["gpus"] else instance["accelerator"]


def container_label(recipe: dict) -> str:
    image = recipe["image"]
    text = f"`{image['repository']}:{image['tag']}`" if image["tag"] else f"`{image['repository']}`"
    if recipe["engine"]["version"]:
        text += f", {recipe['engine']['name']} {recipe['engine']['version']}"
    if image["digest"]:
        text += f", pinned to `{image['digest']}`"
    return text


def capability_summary(recipe: dict) -> str:
    caps = recipe["capabilities"]
    parts = []
    for state, prefix in [(True, "validated"), (False, "failed"), (None, "not tested")]:
        labels = [label.lower() for key, label in CAPABILITIES if caps.get(key) is state]
        if labels:
            parts.append(f"{prefix}: " + ", ".join(labels))
    text = "; ".join(parts)
    return text[0].upper() + text[1:]


def failed_checks_line(recipe: dict) -> str:
    checks = recipe["failed_checks"]
    if not checks:
        return "None"
    return "; ".join(f"`{check}` ({FAILED_CHECKS[check]})" if check in FAILED_CHECKS else f"`{check}`" for check in checks)


def metrics_table(recipe: dict) -> list[str]:
    if not recipe["metrics"]:
        return ["Benchmark results on SageMaker are not available for this recipe yet."]
    lines = [
        "| Workload | Concurrency | Input tokens | Output tokens | Output tok/s | Per-user tok/s | Requests/s | Median TTFT (ms) | Median TPOT (ms) | USD per 1M output tokens |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    order = {suite: i for i, suite in enumerate(SUITES)}
    for m in sorted(recipe["metrics"], key=lambda m: (order.get(m["suite"], len(SUITES)), m["suite"], m["concurrency"] or 0)):
        lines.append(
            "| "
            + " | ".join(
                [
                    f"`{m['suite']}`",
                    fmt(m["concurrency"], 0),
                    fmt(m["input_tokens"], 0),
                    fmt(m["output_tokens"], 0),
                    fmt(m["output_throughput"], 1),
                    fmt(per_user(m), 1),
                    fmt(m["request_throughput"], 2),
                    fmt(m["median_ttft_ms"], 1),
                    fmt(m["median_tpot_ms"], 1),
                    fmt(m["cost_per_million_output_tokens_usd"], 2),
                ]
            )
            + " |"
        )
    measured = recipe["measured"]
    lines += [
        "",
        f"Measured on {measured['date']} on a SageMaker endpoint in `{measured['region']}` with `vllm bench serve`. "
        "Read [How recipes are measured](./methodology) for the workloads and metrics.",
    ]
    return lines


def flag(name: str) -> str:
    return "--" + re.sub(r"^SM_[A-Z]+_", "", name).lower().replace("_", "-")


def settings_table(recipe: dict) -> list[str]:
    lines = ["| Environment variable | Engine argument | Value |", "|---|---|---|"]
    for key, value in sorted(recipe["deployment"]["environment"].items()):
        lines.append(f"| `{key}` | `{flag(key)}` | `{value}` |")
    return lines


