def upload_templates(recipes: list[dict]) -> None:
    import boto3

    s3 = boto3.client("s3", region_name=TEMPLATE_BUCKET_REGION)
    for recipe in recipes:
        s3.put_object(
            Bucket=TEMPLATE_BUCKET,
            Key=f"{TEMPLATE_PREFIX}{recipe['id']}.json",
            Body=cloudformation_template(recipe).encode(),
            ContentType="application/json",
        )
        print(f"uploaded {template_url(recipe)}")


def check_templates(recipes: list[dict]) -> None:
    stale = []
    for recipe in recipes:
        expected = hashlib.md5(cloudformation_template(recipe).encode()).hexdigest()
        request = urllib.request.Request(template_url(recipe), method="HEAD")
        try:
            with urllib.request.urlopen(request, timeout=30) as response:
                etag = response.headers.get("ETag", "").strip('"')
        except urllib.error.HTTPError:
            etag = None
        if etag != expected:
            stale.append(template_url(recipe))
    if stale:
        raise SystemExit(
            "CloudFormation templates are missing or out of date:\n"
            + "\n".join(f"  {url}" for url in stale)
            + "\nRun `python scripts/generate-recipes.py --upload-templates` with AWS credentials for the "
            f"{TEMPLATE_BUCKET} bucket."
        )


def capability_summary(recipe: dict) -> str:
    caps = recipe["capabilities"]
    parts = []
    for state, prefix in [(True, "validated"), (False, "failed"), (None, "not tested")]:
        labels = [label.lower() for key, label in CAPABILITIES if caps.get(key) is state]
        if labels:
            parts.append(f"{prefix}: " + ", ".join(labels))
    text = "; ".join(parts)
    return text[0].upper() + text[1:]


def failed_checks_line(recipe: dict) -> str:
    checks = recipe["validation"]["failed_checks"]
    if not checks:
        return "None"
    return "; ".join(f"`{check}` ({FAILED_CHECKS[check]})" if check in FAILED_CHECKS else f"`{check}`" for check in checks)


def metrics_table(recipe: dict) -> list[str]:
    if not recipe["metrics"]:
        return ["Benchmark results on SageMaker are not available for this recipe."]
    lines = [
        "| Workload | Concurrency | Input tokens | Output tokens | Output tok/s | Per-user tok/s | Requests/s | Median TTFT (ms) | Median TPOT (ms) | USD per 1M output tokens |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    order = {suite: i for i, suite in enumerate(SUITES)}
    for m in sorted(recipe["metrics"], key=lambda m: (order.get(m["suite"], len(SUITES)), m["suite"], m["concurrency"] or 0)):
        lines.append(
            "| "
            + " | ".join(
                [
                    f"`{m['suite']}`",
                    fmt(m["concurrency"], 0),
                    fmt(m["input_tokens"], 0),
                    fmt(m["output_tokens"], 0),
                    fmt(m["output_throughput"], 1),
                    fmt(per_user(m), 1),
                    fmt(m["request_throughput"], 2),
                    fmt(m["median_ttft_ms"], 1),
                    fmt(m["median_tpot_ms"], 1),
                    fmt(m["cost_per_million_output_tokens_usd"], 2),
                ]
            )
            + " |"
        )
    measured = recipe["measured"]
    if measured:
        lines += [
            "",
            f"Measured on {measured['date']} on a SageMaker endpoint in `{measured['region']}` with `{measured['tool']}`. "
            "Read [How recipes are measured](./methodology) for the workloads and metrics.",
        ]
    return lines


def flag(name: str) -> str:
    return "--" + name.removeprefix("SM_VLLM_").lower().replace("_", "-")


def settings_table(recipe: dict) -> list[str]:
    lines = ["| Environment variable | vLLM argument | Value |", "|---|---|---|"]
    for key, value in sorted(recipe["deployment"]["environment"].items()):
        lines.append(f"| `{key}` | `{flag(key)}` | `{value}` |")
    return lines


