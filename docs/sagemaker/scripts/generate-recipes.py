def sagemaker_cli(recipe: dict, gated: bool) -> list[str]:
    environment = dict(recipe["deployment"]["environment"])
    if gated:
        environment["HF_TOKEN"] = "${HF_TOKEN}"
    container = json.dumps({"Image": image_uri(recipe, "${REGION}"), "Environment": environment}, indent=2, sort_keys=False)
    variants = json.dumps(
        [
            {
                "VariantName": "AllTraffic",
                "ModelName": "${NAME}",
                "InstanceType": recipe["instance"]["type"],
                "InitialInstanceCount": 1,
                "InferenceAmiVersion": recipe["deployment"]["inference_ami_version"],
                "ContainerStartupHealthCheckTimeoutInSeconds": recipe["deployment"]["startup_health_check_timeout_s"],
            }
        ],
        indent=2,
    )
    return [
        "The commands create the model, the endpoint configuration, and the endpoint with the "
        "[AWS CLI](https://docs.aws.amazon.com/cli/latest/userguide/getting-started-install.html), and wait until the "
        "endpoint is `InService`. Set `ROLE_ARN` to a SageMaker execution role.",
        "",
        "```bash",
        "# AWS region where the endpoint runs",
        f"REGION={DEFAULT_REGION}",
        f"NAME={endpoint_name(recipe)}",
        "ROLE_ARN=arn:aws:iam::111122223333:role/your-sagemaker-execution-role",
        "",
        "cat > container.json <<EOF",
        container,
        "EOF",
        "cat > variants.json <<EOF",
        variants,
        "EOF",
        "",
        'aws sagemaker create-model --region "$REGION" --model-name "$NAME" \\',
        '  --execution-role-arn "$ROLE_ARN" --primary-container file://container.json',
        'aws sagemaker create-endpoint-config --region "$REGION" --endpoint-config-name "$NAME" \\',
        "  --production-variants file://variants.json",
        'aws sagemaker create-endpoint --region "$REGION" --endpoint-name "$NAME" --endpoint-config-name "$NAME"',
        "",
        "# returns when the endpoint is InService; run it again if it times out after one hour",
        'aws sagemaker wait endpoint-in-service --region "$REGION" --endpoint-name "$NAME"',
        "```",
        "",
        "Delete the endpoint, the endpoint configuration, and the model to stop billing:",
        "",
        "```bash",
        'aws sagemaker delete-endpoint --region "$REGION" --endpoint-name "$NAME"',
        'aws sagemaker delete-endpoint-config --region "$REGION" --endpoint-config-name "$NAME"',
        'aws sagemaker delete-model --region "$REGION" --model-name "$NAME"',
        "```",
    ]


